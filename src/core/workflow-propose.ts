import crypto from "node:crypto";
import { REPO_POLICY_PATH } from "../config.js";
import type { OnboardRunner } from "./onboard.js";
import {
  Workflow,
  classifyChange,
  loosens,
  resolveWorkflow,
  type FieldChange,
  type HostWorkflowInput,
} from "./workflow.js";
import { resolveSkills } from "./skills.js";

export const PROPOSE_BRANCH = "chore/archangel-workflow";
export const LOOSENS_LABEL = "policy:loosens";
const SCOUT_DIR = ".agents/scouts";

export interface RepoFile {
  content: string;
  /** Git blob sha, needed to update the file through the contents API. */
  blobSha: string;
}

/** Reads a file at a ref with the owner's `gh`; null when it does not exist. */
export async function readRepoFile(runner: OnboardRunner, repo: string, ref: string, filePath: string): Promise<RepoFile | null> {
  const url = `repos/${repo}/contents/${filePath}?ref=${ref}`;
  try {
    const blobSha = (await runner.run("gh", ["api", url, "--jq", ".sha"])).trim();
    const content = await runner.run("gh", ["api", url, "-H", "Accept: application/vnd.github.raw"]);
    return blobSha ? { content, blobSha } : null;
  } catch {
    return null;
  }
}

export interface ProposePlan {
  repo: string;
  defaultBranch: string;
  /** sha256 of the file on the default branch now, or null when there is none. */
  currentFileSha256: string | null;
  changes: FieldChange[];
  /** False when the current file is missing or not a valid workflow, so no semantic diff exists. */
  classified: boolean;
  loosens: boolean;
  files: Array<{ path: string; content: string; blobSha: string | null }>;
  title: string;
  body: string;
}

const sha256 = (s: string) => crypto.createHash("sha256").update(s).digest("hex");

/** Server-built PR body: loosened fields first and in bold, then tightened, then plain changes. */
export function buildProposeBody(opts: {
  changes: FieldChange[];
  classified: boolean;
  files: string[];
  landing?: string;
}): string {
  const order = { loosen: 0, tighten: 1, changed: 2 } as const;
  const sorted = [...opts.changes].sort((a, b) => order[a.direction] - order[b.direction] || a.field.localeCompare(b.field));
  const lines = ["Proposed workflow change (generated by `archangel workflow propose`). Review the diff; nothing here merges itself.", ""];
  if (!opts.classified) {
    lines.push("No valid current workflow file on the default branch, so there is no semantic diff. Review the whole file.", "");
  } else if (sorted.length === 0) {
    lines.push("No workflow field changes (only Scout prompt files differ).", "");
  } else {
    lines.push("| Field | Effect |", "|---|---|");
    for (const c of sorted) {
      lines.push(
        c.direction === "loosen"
          ? `| **${c.field}** | **LOOSENS** |`
          : `| ${c.field} | ${c.direction === "tighten" ? "tightens" : "changed: read it (no safe ordering)"} |`,
      );
    }
    lines.push("");
  }
  if (opts.landing) lines.push(`Effective bugfix landing after host limits: ${opts.landing}`, "");
  lines.push(`Files: ${opts.files.join(", ")}`);
  return lines.join("\n");
}

/**
 * Validates the proposed workflow against the schema and kernel, compares it with the default branch,
 * and returns the plan. Reads only.
 */
export async function planWorkflowProposal(
  runner: OnboardRunner,
  repo: string,
  proposedRaw: string,
  opts: { baseFileSha256?: string; scoutPrompts?: Record<string, string>; host?: HostWorkflowInput } = {},
): Promise<ProposePlan> {
  if (!/^[\w.-]+\/[\w.-]+$/.test(repo)) throw new Error(`Expected owner/name, got '${repo}'`);
  let json: unknown;
  try {
    json = JSON.parse(proposedRaw);
  } catch (err) {
    throw new Error(`Proposed file is not valid JSON: ${err instanceof Error ? err.message : String(err)}`);
  }
  const parsed = Workflow.safeParse(json);
  if (!parsed.success) {
    throw new Error(
      `Proposed workflow is invalid: ${parsed.error.issues.map((i) => `${i.path.join(".") || "(root)"}: ${i.message}`).join("; ")}`,
    );
  }
  const proposed = parsed.data;
  const prompts = opts.scoutPrompts ?? {};
  for (const s of proposed.scouts) {
    if (prompts[s.name] === undefined) throw new Error(`Scout '${s.name}' has no prompt file (${SCOUT_DIR}/${s.name}.md) in the proposal`);
    try {
      resolveSkills(s.skills);
    } catch (err) {
      throw new Error(`Scout '${s.name}': ${err instanceof Error ? err.message : String(err)}`);
    }
  }

  const defaultBranch = (await runner.run("gh", ["repo", "view", repo, "--json", "defaultBranchRef", "-q", ".defaultBranchRef.name"])).trim();
  const current = await readRepoFile(runner, repo, defaultBranch, REPO_POLICY_PATH);
  const currentSha = current ? sha256(current.content) : null;
  if (opts.baseFileSha256 !== undefined && opts.baseFileSha256 !== (currentSha ?? "")) {
    throw new Error(
      `Stale draft: ${REPO_POLICY_PATH} on ${defaultBranch} changed since the draft was based on it (now ${currentSha?.slice(0, 12) ?? "absent"}). Rebase the draft and retry.`,
    );
  }
  const open = (
    await runner.run("gh", ["pr", "list", "--repo", repo, "--head", PROPOSE_BRANCH, "--state", "open", "--json", "url", "-q", ".[0].url"])
  ).trim();
  if (open) throw new Error(`A workflow proposal PR is already open: ${open}`);

  let changes: FieldChange[] = [];
  let classified = false;
  if (current) {
    try {
      const prev = Workflow.parse(JSON.parse(current.content));
      changes = classifyChange(prev, proposed);
      classified = true;
    } catch {
      // current file is not a valid workflow: nothing to compare against
    }
  }

  const files: ProposePlan["files"] = [];
  const normalized = JSON.stringify(json, null, 2) + "\n";
  if (current?.content !== normalized) files.push({ path: REPO_POLICY_PATH, content: normalized, blobSha: current?.blobSha ?? null });
  for (const s of proposed.scouts) {
    const path = `${SCOUT_DIR}/${s.name}.md`;
    const body = prompts[s.name]!.trim() + "\n";
    const existing = await readRepoFile(runner, repo, defaultBranch, path);
    if (existing?.content !== body) files.push({ path, content: body, blobSha: existing?.blobSha ?? null });
  }
  if (files.length === 0) throw new Error("The proposal is identical to the current workflow files; nothing to propose.");

  let landing: string | undefined;
  if (opts.host) {
    const eff = resolveWorkflow(opts.host, {
      repo,
      mainSha: "proposal",
      fileRaw: proposedRaw,
      scoutPrompts: prompts,
    });
    if (eff.status === "ok") {
      landing = `${eff.landingBugfix.value} (source: ${eff.landingBugfix.source}${eff.landingBugfix.declared ? `; repo declares ${eff.landingBugfix.declared}` : ""})`;
    }
  }
  return {
    repo,
    defaultBranch,
    currentFileSha256: currentSha,
    changes,
    classified,
    loosens: loosens(changes),
    files,
    title: "chore: update Archangel workflow",
    body: buildProposeBody({ changes, classified, files: files.map((f) => f.path), landing }),
  };
}

/**
 * Opens one PR with the owner's `gh`: the new workflow file (and changed Scout prompts) on
 * `chore/archangel-workflow`, labelled `policy:loosens` only when something loosens. Never merges.
 * With `dryRun` it prints the plan and makes no mutating call.
 */
export async function proposeWorkflow(
  runner: OnboardRunner,
  repo: string,
  proposedRaw: string,
  opts: {
    baseFileSha256?: string;
    scoutPrompts?: Record<string, string>;
    host?: HostWorkflowInput;
    dryRun?: boolean;
    log?: (s: string) => void;
  } = {},
): Promise<{ plan: ProposePlan; url: string | null }> {
  const log = opts.log ?? console.log;
  const plan = await planWorkflowProposal(runner, repo, proposedRaw, opts);
  log(`Proposal for ${repo} (default branch ${plan.defaultBranch}): ${plan.files.map((f) => f.path).join(", ")}`);
  log(plan.body);
  log(plan.loosens ? `Label: ${LOOSENS_LABEL}` : "No loosening detected: no label.");
  if (opts.dryRun) {
    log("Dry run: nothing changed.");
    return { plan, url: null };
  }

  const tip = (await runner.run("gh", ["api", `repos/${repo}/git/ref/heads/${plan.defaultBranch}`, "--jq", ".object.sha"])).trim();
  // Re-read just before writing: a change since planning means the plan is stale.
  const again = await readRepoFile(runner, repo, plan.defaultBranch, REPO_POLICY_PATH);
  if ((again ? sha256(again.content) : null) !== plan.currentFileSha256) {
    throw new Error(`Stale: ${REPO_POLICY_PATH} on ${plan.defaultBranch} changed while planning. Retry.`);
  }
  if (plan.loosens) {
    const labels = (await runner.run("gh", ["label", "list", "--repo", repo, "--limit", "200", "--json", "name", "-q", ".[].name"]))
      .split("\n")
      .map((l) => l.trim());
    if (!labels.includes(LOOSENS_LABEL)) {
      await runner.run("gh", ["label", "create", LOOSENS_LABEL, "--repo", repo, "--color", "d93f0b", "--description", "Archangel workflow change that loosens a limit"]);
    }
  }
  await runner.run("gh", ["api", "-X", "POST", `repos/${repo}/git/refs`, "-f", `ref=refs/heads/${PROPOSE_BRANCH}`, "-f", `sha=${tip}`]);
  for (const f of plan.files) {
    await runner.run("gh", [
      "api", "-X", "PUT", `repos/${repo}/contents/${f.path}`,
      "-f", `message=chore: update ${f.path} (Archangel workflow)`,
      "-f", `content=${Buffer.from(f.content).toString("base64")}`,
      ...(f.blobSha ? ["-f", `sha=${f.blobSha}`] : []),
      "-f", `branch=${PROPOSE_BRANCH}`,
    ]);
  }
  const url = (
    await runner.run("gh", [
      "pr", "create", "--repo", repo, "--head", PROPOSE_BRANCH, "--base", plan.defaultBranch,
      "--title", plan.title, "--body", plan.body,
      ...(plan.loosens ? ["--label", LOOSENS_LABEL] : []),
    ])
  ).trim();
  log(`Opened ${url}`);
  return { plan, url };
}
